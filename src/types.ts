import type { Diagnosis } from './services/ipaAligner';

export type Tier = 1 | 2 | 3;
export type RegisterBadge = 'GREEN_EXECUTIVE_SAFE' | 'AMBER_COLLEAGUE' | 'RED_COLLOQUIAL';

export interface VocabEntry {
  id: string;
  headword: string;
  ipa_rp: string;
  syllable_stress: string;
  audio_uri: string | null;
  phonetic_trap: string;
  register_badge: RegisterBadge;
  register_label: string;
  usage_context: string;
  pragmatic_note: string;
  replaces_verbose: string[];
  collocations: string[];
  examples_rp: { text: string; ipa_connected: string; audio_uri?: string }[];
  /** extra surface forms that count as deploying the item (inflections, variants) */
  forms?: string[];
  /** canonical RP phonemes in the headword (generated by scripts/annotate-data.mjs) */
  phonemes?: string[];
  // --- lexicon cards (public/lexicon) ---
  source?: 'core' | 'lexicon' | 'auto';
  category?: string;
  gloss?: string;
  us_equivalent?: string | null;
  pitfall?: string | null;
  /** Wikipedia article title and validated lead-image thumbnail */
  wiki?: string | null;
  img?: string | null;
  /** auto words: part of speech, frequency rank, example attribution */
  pos?: string;
  rank?: number;
  /** frequency band (1 = top 1,000) */
  band?: number;
  exampleSource?: { name: string; url: string; license: string } | null;
}

export interface LexiconIndex {
  version: number;
  categories: { id: string; name: string; file: string; count: number }[];
  curated: number;
  wordShards: { file: string; from: number; to: number; count: number }[];
  words: number;
  licences: { name: string; url?: string; license?: string; note?: string }[];
}

/** Automatic word row as shipped in public/lexicon/words-NN.json */
export interface WordRow {
  w: string;
  r: number;
  p: string;
  d: string;
  x?: string;
  xs?: string;
  xb?: string;
  /** stressed RP IPA */
  i: string;
  ph: string;
}

export interface RedundancyRule {
  id: string;
  /** JavaScript regular-expression source, compiled case-insensitively */
  pattern: string;
  replacements: string[];
  category: 'scaffold' | 'filler' | 'wordy' | 'pleonasm' | 'indianism' | 'hedge' | 'intensifier' | 'upgrade';
  severity: 'critical' | 'minor';
  register?: RegisterBadge;
  note: string;
  /** vocab ids this rule promotes */
  vocab?: string[];
}

export type Pillar = 'schwa' | 'alveolar' | 'diphthong' | 'vw' | 'rhotic' | 'vowelspace' | 'th' | 'mixed';

export interface Prompt {
  id: string;
  tier: Tier;
  pillar?: Pillar;
  category: string;
  title: string;
  /** Tier 1: text to read aloud · Tier 2: verbose paragraph · Tier 3: scenario */
  text: string;
  /** Tier 1: the same text · Tier 2: a model concise answer · Tier 3: optional model answer */
  reference?: string;
  targetVocab: string[];
  timeLimitSec: number;
  /** canonical RP phonemes the prompt exercises (generated by scripts/annotate-data.mjs) */
  phonemes?: string[];
  /** Tier 1 minimal pairs, e.g. [["ship","sheep"]] */
  pairs?: [string, string][];
  /**
   * "shadow" = listen to the neural RP voice, then repeat (endless corpus).
   * "nameit" = say the British word for a picture / American term / definition.
   */
  mode?: 'shadow' | 'nameit';
  /** lexicon entry this prompt practises (Words mode) */
  cardId?: string;
  /** corpus difficulty level (1–12) */
  level?: number;
  /** attribution for corpus items */
  source?: { name: string; by?: string; license: string; url: string };
  /** generated practice step: a build-up of a failed sentence, or a rung of a sound ladder */
  drill?: BuildUpDrill | LadderDrill;
}

/** One step of breaking a failed sentence down: a problem word, then phrases built from the end. */
export interface BuildUpDrill {
  kind: 'buildup';
  /** the sentence being broken down */
  parent: Prompt;
  /** 0-based step, of `steps` */
  step: number;
  steps: number;
  part: 'word' | 'phrase';
}

/** Ladder rungs, easiest first: example words, minimal pairs, short phrases, sentences. */
export type LadderStage = 1 | 2 | 3 | 4;
export interface LadderDrill {
  kind: 'ladder';
  phoneme: string;
  stage: LadderStage;
  /** what the step shows; rare sounds without pairs or sentences fall back to simpler content */
  content: 'words' | 'pairs' | 'phrase' | 'sentence';
  /** the sound it is most often confused with (minimal pairs contrast the two) */
  contrast?: string;
}

/** Progress on one sound's ladder; stage 5 means the ladder is complete. */
export interface LadderProgress {
  stage: LadderStage | 5;
  /** passes at the current stage */
  wins: number;
  updatedAt: number;
}

export interface CorpusIndex {
  version: number;
  total: number;
  levels: { level: number; file: string; count: number; passages: number }[];
  sources: { id: string; name: string; license: string; url: string; itemUrl?: string }[];
}

/** Compact corpus row as shipped in public/corpus/level-NN.json */
export interface CorpusRow {
  id: string;
  text: string;
  src: string;
  by: string;
  /** RP phoneme indices encoded as characters (code − 48 = index into RP_PHONEMES) */
  ph?: string;
}

export interface PhonemeInfo {
  symbol: string;
  kind: 'vowel' | 'consonant';
  keyword: string;
  examples: string[];
  description: string;
  mechanics: string;
  /** vowel trapezium coords (0..1) or consonant grid cell */
  chart: { x: number; y: number } | { place: string; manner: string; voiced: boolean };
  interference?: { phone: string; label: string; fix: string }[];
}

export interface CuratedData {
  phonemes: PhonemeInfo[];
  vocab: VocabEntry[];
  rules: RedundancyRule[];
  prompts: Prompt[];
  calibration?: import('./services/ipaAligner').AcousticCalibration | null;
}

// --- persisted state -------------------------------------------------------

export interface ConfusionState {
  /** 44 rows × CONFUSION_COLUMNS.length; each row is a probability distribution (EWMA) */
  rows: number[][];
  /** total observations per row */
  counts: number[];
  /** observations per row since the last successful sync (for EWMA merge) */
  pending: number[];
  updatedAt: number[];
}

export interface Ewma { value: number; n: number }

export interface LearnerState {
  id: 'learner';
  version: 1;
  confusion: ConfusionState;
  /** EWMA rate of each interference habit per opportunity */
  habits: Partial<Record<Diagnosis, Ewma>>;
  /** V_R: r_schwa, r_nPVI, r_fluency, r_concise */
  prosody: { schwa: Ewma; npvi: Ewma; fluency: Ewma; concise: Ewma };
  totalTurns: number;
  /** current listen-and-repeat corpus level (1–12) */
  shadowLevel?: number;
  /** current frequency band (1 = top 1,000 words) for Words mode */
  wordBand?: number;
  /** sound ladders by phoneme (absent in state saved before ladders existed) */
  ladders?: Record<string, LadderProgress>;
  updatedAt: number;
}

export interface VocabCard {
  id: string;
  stability: number;
  difficulty: number;
  reps: number;
  lapses: number;
  lastReview: number | null;
  due: number;
  /** spoken retrieval fluency τ (EWMA of hesitation-free deployment) */
  tau: number;
  history: { t: number; grade: 1 | 2 | 3 | 4; ctx: 'tier1' | 'tier2' | 'tier3' }[];
  updatedAt: number;
}

export interface PromptStat {
  id: string;
  n: number;
  lastServed: number;
  bestReward: number;
  passed: boolean;
  updatedAt: number;
}

