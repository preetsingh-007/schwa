def rx(phrase: str) -> str:
    return phrase.replace(' ', r'\s+')

RULES = []
def add(pattern, repl, cat, sev, note='', vocab=None):
    RULES.append({
        'pattern': r'\b' + rx(pattern) + (r'\b' if pattern[-1].isalnum() or pattern.endswith(')') or pattern.endswith('?') and pattern[-2] == ')' else ''),
        'replacements': repl if isinstance(repl, list) else [repl],
        'category': cat, 'severity': sev, 'note': note, **({'vocab': vocab} if vocab else {}),
    })

for p, r, sev, note, vocab in UPGRADES:
    add(p, r, 'upgrade', sev, note, vocab)
for p, r in SCAFFOLDS:
    add(p, r, 'scaffold', C, 'Verbal scaffolding: it delays the point. Start with the point itself.')
for p in FILLERS:
    add(p, [''], 'filler', M, 'Filler — silence is better than a filler.')
for p, r in WORDY:
    add(p, [r], 'wordy', M, f"Wordy phrase — '{r}' says the same." if r else 'Wordy phrase — cut it.')
for p, r in PLEONASMS:
    add(p, [r], 'pleonasm', M, 'Redundant pair (pleonasm): one word already carries the meaning.')
for p, r, note in INDIANISMS:
    add(p, [r], 'indianism', C, note or 'Indian-English usage that reads oddly to British listeners.')
for p, r in HEDGES:
    add(p, [r], 'hedge', M, 'Stacked hedges sound unsure; one well-placed hedge is very British.')
for p, r in INTENSIFIERS:
    add(p, [r], 'intensifier', M, 'Stacked intensifiers — pick one precise word instead.')

